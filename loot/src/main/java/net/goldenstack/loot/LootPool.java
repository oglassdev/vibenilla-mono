package net.goldenstack.loot;

import java.util.ArrayList;
import java.util.List;
import net.minestom.server.codec.StructCodec;
import net.minestom.server.item.ItemStack;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

/**
 * A loot pool.
 *
 * @param rolls the default number of rolls to occur
 * @param bonusRolls the number of bonus rolls to occur. Multiplied by the context's luck.
 * @param entries the entries to generate loot from.
 * @param predicates the predicates for loot generation
 * @param functions the modifiers applied to each item
 */
public record LootPool(
        @NotNull LootNumber rolls,
        @NotNull LootNumber bonusRolls,
        @NotNull List<LootEntry> entries,
        @NotNull List<LootPredicate> predicates,
        @NotNull List<LootFunction> functions)
        implements LootGenerator {

    @SuppressWarnings("UnstableApiUsage")
    public static final @NotNull StructCodec<LootPool> CODEC =
            StructCodec.struct(
                    "rolls",
                    LootNumber.CODEC,
                    LootPool::rolls,
                    "bonus_rolls",
                    LootNumber.CODEC.optional(new LootNumber.Constant(0D)),
                    LootPool::bonusRolls,
                    "entries",
                    LootEntry.CODEC.list(),
                    LootPool::entries,
                    "condition",
                    LootPredicate.CODEC.listOrSingle().optional(List.of()),
                    LootPool::predicates,
                    "modifier",
                    LootFunction.CODEC.listOrSingle().optional(List.of()),
                    LootPool::functions,
                    LootPool::new);

    @Override
    public @NotNull List<ItemStack> generate(@NotNull LootContext context) {
        if (!LootPredicate.all(this.predicates, context)) {
            return List.of();
        }

        var rolls = this.rolls.getInt(context);

        var luck = context.get(LootContext.LUCK);
        if (luck != null) {
            var bonusRolls = (float) this.bonusRolls.getDouble(context);
            rolls += (int) Math.floor(bonusRolls * luck.floatValue());
        }

        var items = new ArrayList<ItemStack>();

        for (var roll = 0; roll < rolls; roll++) {
            var choice = pickChoice(this.entries, context);

            if (choice == null) {
                continue;
            }

            items.addAll(choice.generate(context));
        }

        return LootFunction.apply(this.functions, items, context);
    }

    /**
     * Picks a random choice from the choices generated by the provided entries, weighted with each
     * choice's weight. If no choices were generated, null is returned.
     *
     * @param entries the entries to generate choices to choose from
     * @param context the context, to use if needed
     * @return the picked choice, or null if no choices were generated
     */
    static @Nullable LootEntry.Choice pickChoice(
            @NotNull List<LootEntry> entries, @NotNull LootContext context) {
        var choices = new ArrayList<LootEntry.Choice>();

        for (var entry : entries) {
            choices.addAll(entry.requestChoices(context));
        }

        if (choices.isEmpty()) {
            return null;
        }

        var weightedChoices = new ArrayList<LootEntry.Choice>();
        var weights = new ArrayList<Long>();

        for (var choice : choices) {
            var weight = choice.getWeight(context);

            if (weight > 0L) {
                weightedChoices.add(choice);
                weights.add(weight);
            }
        }

        if (weightedChoices.isEmpty()) {
            return null;
        }

        if (weightedChoices.size() == 1) {
            return weightedChoices.getFirst();
        }

        var totalWeight = 0L;
        var weightMilestones = new long[weightedChoices.size()];
        var weightIndex = 0;

        for (var weight : weights) {
            totalWeight += weight;
            weightMilestones[weightIndex] = totalWeight;
            weightIndex++;
        }

        var random = context.require(LootContext.RANDOM);
        var value =
                totalWeight <= Integer.MAX_VALUE
                        ? random.nextInt((int) totalWeight)
                        : random.nextLong(totalWeight);

        var choice = weightedChoices.getLast();

        weightIndex = 0;

        for (var weightMilestone : weightMilestones) {
            if (value < weightMilestone) {
                choice = weightedChoices.get(weightIndex);
                break;
            }
            weightIndex++;
        }

        return choice;
    }
}
