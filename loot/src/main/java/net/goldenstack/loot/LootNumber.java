package net.goldenstack.loot;

import java.util.List;
import net.goldenstack.loot.util.nbt.NBTPath;
import net.kyori.adventure.key.Key;
import net.kyori.adventure.nbt.CompoundBinaryTag;
import net.kyori.adventure.nbt.IntBinaryTag;
import net.kyori.adventure.nbt.NumberBinaryTag;
import net.minestom.server.codec.Codec;
import net.minestom.server.codec.StructCodec;
import net.minestom.server.item.enchant.LevelBasedValue;
import net.minestom.server.registry.DynamicRegistry;
import org.jetbrains.annotations.NotNull;

/** Generates numbers based on provided loot contexts. */
@SuppressWarnings("UnstableApiUsage")
public interface LootNumber {

    @NotNull
    Codec<LootNumber> CODEC =
            Codec.FLOAT
                    .<LootNumber>transform(
                            value -> new Constant((double) value),
                            value -> ((Constant) value).value().floatValue())
                    .orElse(
                            Codec.RegistryTaggedUnion(
                                    registries -> {
                                        class Holder {
                                            static final @NotNull DynamicRegistry<
                                                            StructCodec<? extends LootNumber>>
                                                    CODEC = createDefaultRegistry();
                                        }
                                        return Holder.CODEC;
                                    },
                                    LootNumber::codec,
                                    "type"));

    static @NotNull DynamicRegistry<StructCodec<? extends LootNumber>> createDefaultRegistry() {
        final DynamicRegistry<StructCodec<? extends LootNumber>> registry =
                DynamicRegistry.create(Key.key("loot_numbers"));
        registry.register("binomial", Binomial.CODEC);
        registry.register("constant", Constant.CODEC);
        registry.register("enchantment_level", EnchantmentLevel.CODEC);
        registry.register("environment_attribute", EnvironmentAttribute.CODEC);
        registry.register("score", Score.CODEC);
        registry.register("storage", Storage.CODEC);
        registry.register("sum", Sum.CODEC);
        registry.register("uniform", Uniform.CODEC);
        return registry;
    }

    /**
     * Generates an integer depending on the information in the provided context.<br>
     * This is an explicitly impure method—it depends on state outside the given context.
     *
     * @param context the context object, to use if required
     * @return the integer generated by this loot number for the provided context
     */
    int getInt(@NotNull LootContext context);

    /**
     * Generates a double depending on the information in the provided context.<br>
     * This is an explicitly impure method—it depends on state outside the given context.
     *
     * @param context the context object, to use if required
     * @return the double generated by this loot number for the provided context
     */
    double getDouble(@NotNull LootContext context);

    /**
     * @return the codec that can encode this number
     */
    @NotNull
    StructCodec<? extends LootNumber> codec();

    record Binomial(@NotNull LootNumber trials, @NotNull LootNumber probability)
            implements LootNumber {
        public static final @NotNull StructCodec<Binomial> CODEC =
                StructCodec.struct(
                        "n",
                        LootNumber.CODEC,
                        Binomial::trials,
                        "p",
                        LootNumber.CODEC,
                        Binomial::probability,
                        Binomial::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            var trials = this.trials.getInt(context);
            var probability = (float) this.probability.getDouble(context);
            var random = context.require(LootContext.RANDOM);

            var successes = 0;
            for (var trial = 0; trial < trials; trial++) {
                if (random.nextFloat() < probability) {
                    successes++;
                }
            }
            return successes;
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            return this.getInt(context);
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record Constant(@NotNull Double value) implements LootNumber {
        public static final @NotNull StructCodec<Constant> CODEC =
                StructCodec.struct(
                        "value",
                        Codec.FLOAT.transform(value -> (double) value, value -> value.floatValue()),
                        Constant::value,
                        Constant::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            return (int) Math.round(this.value.floatValue());
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            return this.value;
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record EnchantmentLevel(@NotNull LevelBasedValue amount) implements LootNumber {
        public static final @NotNull StructCodec<EnchantmentLevel> CODEC =
                StructCodec.struct(
                        "amount",
                        LevelBasedValue.CODEC,
                        EnchantmentLevel::amount,
                        EnchantmentLevel::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            return (int) Math.round(this.getDouble(context));
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            return this.amount.calc(context.require(LootContext.ENCHANTMENT_LEVEL));
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record Score(@NotNull LootScore target, @NotNull String objective, double scale)
            implements LootNumber {
        private static final @NotNull Codec<Double> SCALE_CODEC =
                Codec.FLOAT.transform(value -> (double) value, value -> value.floatValue());

        public static final @NotNull StructCodec<Score> CODEC =
                StructCodec.struct(
                        "target",
                        LootScore.CODEC,
                        Score::target,
                        "score",
                        Codec.STRING,
                        Score::objective,
                        "scale",
                        SCALE_CODEC.optional(1.0),
                        Score::scale,
                        Score::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            return (int) Math.round(this.getDouble(context));
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            var score = this.target.apply(context).apply(this.objective);

            return score != null ? (float) (score * (float) this.scale) : 0.0F;
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record Storage(@NotNull Key storage, @NotNull NBTPath path) implements LootNumber {
        public static final @NotNull StructCodec<Storage> CODEC =
                StructCodec.struct(
                        "storage",
                        Codec.KEY,
                        Storage::storage,
                        "path",
                        NBTPath.CODEC,
                        Storage::path,
                        Storage::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            return this.get(context).intValue();
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            return this.get(context).doubleValue();
        }

        private NumberBinaryTag get(@NotNull LootContext context) {
            var compound = context.vanilla().commandStorage(this.storage);

            var refs = this.path.get(compound != null ? compound : CompoundBinaryTag.empty());
            if (refs.size() != 1) return IntBinaryTag.intBinaryTag(0);

            if (refs.getFirst().get() instanceof NumberBinaryTag number) {
                return number;
            } else {
                return IntBinaryTag.intBinaryTag(0);
            }
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record EnvironmentAttribute(@NotNull Key attribute) implements LootNumber {
        public static final @NotNull StructCodec<EnvironmentAttribute> CODEC =
                StructCodec.struct(
                        "attribute",
                        Codec.KEY,
                        EnvironmentAttribute::attribute,
                        EnvironmentAttribute::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            return Math.round((float) this.getDouble(context));
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            var value = context.vanilla().environmentAttribute(this.attribute, context);
            return value instanceof NumberBinaryTag number ? number.doubleValue() : 0.0;
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record Sum(@NotNull List<LootNumber> summands) implements LootNumber {
        public static final @NotNull StructCodec<Sum> CODEC =
                StructCodec.struct("summands", LootNumber.CODEC.list(), Sum::summands, Sum::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            var value = 0.0F;

            for (var summand : this.summands) {
                value += (float) summand.getDouble(context);
            }

            return (int) Math.floor(value);
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            var value = 0.0F;

            for (var summand : this.summands) {
                value += (float) summand.getDouble(context);
            }

            return value;
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }

    record Uniform(@NotNull LootNumber min, @NotNull LootNumber max) implements LootNumber {
        public static final @NotNull StructCodec<Uniform> CODEC =
                StructCodec.struct(
                        "min",
                        LootNumber.CODEC,
                        Uniform::min,
                        "max",
                        LootNumber.CODEC,
                        Uniform::max,
                        Uniform::new);

        @Override
        public int getInt(@NotNull LootContext context) {
            var minimum = this.min.getInt(context);
            var maximum = this.max.getInt(context);

            if (minimum >= maximum) {
                return minimum;
            }

            return context.require(LootContext.RANDOM).nextInt(maximum - minimum + 1) + minimum;
        }

        @Override
        public double getDouble(@NotNull LootContext context) {
            var minimum = (float) this.min.getDouble(context);
            var maximum = (float) this.max.getDouble(context);

            if (minimum >= maximum) {
                return minimum;
            }

            var random = context.require(LootContext.RANDOM);
            return minimum + random.nextFloat() * (maximum - minimum);
        }

        @Override
        public @NotNull StructCodec<? extends LootNumber> codec() {
            return CODEC;
        }
    }
}
